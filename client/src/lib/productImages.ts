export function getSafetyScore(productId: string): number {
  const hash = (s: string) => {
    let h = 5381;
    for (let i = 0; i < s.length; i++) h = ((h << 5) - h + s.charCodeAt(i)) | 0;
    return Math.abs(h);
  };
  // Les grandes marques internationales ont un score plus élevé
  const topBrands = ["cerave", "lrp", "neutrogena", "bioderma", "loreal", "ambi", "fair-white", "kojie"];
  const goodBrands = ["garnier", "nivea", "dove", "vaseline", "palmers", "pantene", "dark-lovely", "cantu", "ors", "schwarzkopf", "africas", "jamaican", "head-shoulders"];
  if (topBrands.some(b => productId.startsWith(b))) return 92 + (hash(productId) % 8);
  if (goodBrands.some(b => productId.startsWith(b))) return 85 + (hash(productId) % 10);
  return 78 + (hash(productId) % 14);
}
